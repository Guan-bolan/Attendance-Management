-- 006_entry_photo_slot.sql —— 给 entry_photos 加 slot（纯加法：只加一列，不动既有列 / 索引 / 数据）
--
-- 为什么要这一列：
--   001 的 `entry_photos` 只记「这条记录挂了哪几张照片」，**不记哪张是上班照**。
--   于是界面只能把「照片 id 升序第 1 张 = 上班照、第 2 张 = 下班照」当口径（IS-006）。
--   那个口径有一个真实的反例：**只拍了/只挂了「下班照」一张**时，它是唯一一张，
--   于是被显示成「上班照」——对账时人会照着角标去认时间，认错了就是错账。
--   所以「上班 / 下班」必须是**库里的数据**，不能是读出顺序的副产品。
--
-- 列语义：
--   * `IN`  = 上班照；`OUT` = 下班照；
--   * **可空**：老数据一律留 NULL = 「未指定」。读出时按 `repo/entries.ts#resolvePhotoSlots`
--     兜底成「id 升序第 1 张 IN、其余 OUT」（与 006 之前的显示逐字一致），但**不回写库**——
--     库里的 NULL 是诚实的「当年没记」，不是「我们猜它是上班照」；
--   * CHECK 只约束「写进去的值」：NULL 通过（`NULL IN (...) ` 不成立，但 CHECK 对 NULL 视为未知 →
--     放行），这是可空列的标准行为；写入路径在 `repo/entries.ts#normalizeSlot` 另有一层 E_VALIDATION。
--
-- 规则（与 001/002/003/004/005 同一套约定）：
--   1. **纯加法**：不重建表、不删列、不动既有索引与数据；
--   2. 由 db/migrate.ts 在**单个事务内**执行，失败整段回滚（版本号也不会前进）；
--   3. 不写 PRAGMA（连接级设置在 openDb 里做）；
--   4. 老库升级后 `entry_photos` 的既有行 `slot` 全是 NULL（SQLite 加列时按默认值填，这里是 NULL）。

ALTER TABLE entry_photos ADD COLUMN slot TEXT CHECK (slot IN ('IN', 'OUT'));
